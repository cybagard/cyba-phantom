func spaced(s string, n int) string { return s + strings.Repeat(" ", n-len(s)) }

// manyRoutes gives n routes with different paths.
func manyRoutes(n int) string {
	var rs []string
	for i := range n {
		rs = append(rs, fmt.Sprintf(`{"path":"/p%d",%s,%s}`, i, ti, ty))
	}
	return rt(rs...)
}

