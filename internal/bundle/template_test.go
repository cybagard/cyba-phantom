var update = flag.Bool("update", false, "write the bundle fixtures into test/fixtures/bundles")

const fixtureDir = "../../test/fixtures/bundles"

// vhostFile is the one template file of the fixtures.
const vhostFile = "vhosts/h.example/index.html"

// bundleFixtures makes the bytes of each fixture file. Each one has a version
// above the running version 2, so that it passes the checks before its own.
// The files hold no signature. The tests sign them with test keys.
func bundleFixtures() map[string][]byte {
	page := ent{name: vhostFile, data: []byte("<p>{{.Title}}</p>\n")}
	mk := func(manifest string, more ...ent) []byte {
		return build(append([]ent{{name: "manifest.json", data: []byte(manifest)}}, more...)...)
	}
	return map[string][]byte{
		"valid.cbnd":         mk(mf(ver(3)), page),
		"badsig.cbnd":        mk(mf(ver(3))),
		"expired.cbnd":       mk(mf(ver(3), expiredRepl...)),
		"minengine.cbnd":     mk(mf(ver(3), engineRepl...)),
		"malformed.cbnd":     mk("{}"),
		"templateparse.cbnd": mk(mf(ver(3)), ent{name: vhostFile, data: []byte("{{if}}\n")}),
	}
}

// T-U-08: the committed files are the files that the generator makes. With
// -update, the test writes them. No other .cbnd file is in the directory.
func TestTU08FixturesAreCurrent(t *testing.T) {
	want := bundleFixtures()
	if *update {
		must(t, os.MkdirAll(fixtureDir, 0o755))
		for name, b := range want {
			must(t, os.WriteFile(filepath.Join(fixtureDir, name), b, 0o644))
		}
	}
	have, err := filepath.Glob(filepath.Join(fixtureDir, "*.cbnd"))
	must(t, err)
	var names []string
	for _, p := range have {
		names = append(names, filepath.Base(p))
	}
	if !slices.Equal(names, slices.Sorted(maps.Keys(want))) {
		t.Fatalf("files %v; want %v", names, slices.Sorted(maps.Keys(want)))
	}
	for name, b := range want {
		got, err := os.ReadFile(filepath.Join(fixtureDir, name))
		must(t, err)
		if !bytes.Equal(got, b) {
			t.Errorf("%s differs from the generated bytes; run make fixtures", name)
		}
	}
}

// T-U-08: each committed bad fixture, loaded on a running bundle, gives its one
// code. The running bundle and the files do not change. valid loads.
func TestTU08FixtureCodes(t *testing.T) {
	otherPriv, _ := testKey(9, "k1")
	for _, c := range []struct {
		file string
		want error
	}{
		{"badsig.cbnd", ErrBadSig},
		{"expired.cbnd", ErrExpired},
		{"minengine.cbnd", ErrMinEngine},
		{"malformed.cbnd", ErrManifestInvalid},
		{"templateparse.cbnd", ErrTemplateParse},
		{"valid.cbnd", nil},
	} {
		t.Run(c.file, func(t *testing.T) {
			arch, err := os.ReadFile(filepath.Join(fixtureDir, c.file))
			must(t, err)
			e := running(t)
			priv := e.priv
			if c.file == "badsig.cbnd" {
				priv = otherPriv
			}
			e.write("bundle/current.cbnd", arch)
			e.write("bundle/current.sig", []byte(sigRow("k1", ed25519.Sign(priv, SigMessage(arch)))))
			if c.want != nil {
				e.rejects(e.l, false, c.want)
				return
			}
			b, err := e.l.Load(false)
			must(t, err)
			if b.Manifest().Version != ver(3) || e.l.Current() != b {
				t.Errorf("running version %s", e.l.Current().Manifest().Version)
			}
		})
	}
}

// loadWith loads a signed bundle of version 3 that has these files, on a
// running bundle. It gives the error of the load.
func loadWith(t *testing.T, ents ...ent) error {
	t.Helper()
	e := running(t)
	arch := build(append([]ent{{name: "manifest.json", data: []byte(mf(ver(3)))}}, ents...)...)
	e.write("bundle/current.cbnd", arch)
	e.write("bundle/current.sig", e.sign(arch))
	_, err := e.l.Load(false)
	return err
}

// T-U-08, SEC-23: a template that does not parse gives template_parse. A
// valid template, a file outside vhosts/ and no template load.
func TestTU08TemplateParse(t *testing.T) {
	f := func(name, text string) ent { return ent{name: name, data: []byte(text)} }
	for _, c := range []struct {
		name string
		ents []ent
		want error
	}{
		{"syntax error", []ent{f(vhostFile, "{{if}}")}, ErrTemplateParse},
		{"undefined function", []ent{f(vhostFile, "{{shell `id`}}")}, ErrTemplateParse},
		{"one bad file of two", []ent{f(vhostFile, "ok"), f("vhosts/h.example/b.txt", "{{")}, ErrTemplateParse},
		{"valid", []ent{f(vhostFile, "<p>{{.Title}}</p>")}, nil},
		{"outside vhosts", []ent{f("traps/x.html", "{{if}}")}, nil},
		{"no template", nil, nil},
	} {
		t.Run(c.name, func(t *testing.T) {
			if err := loadWith(t, c.ents...); err != c.want {
				t.Errorf("got %v; want %v", err, c.want)
			}
		})
	}
}

// SEC-23: the parse gives the fixed error, with no template text.
